export function calculateDosage(mgPeptide, mlWater, doseMg) {
  const concentration = mgPeptide / mlWater; // mg per ml
  const doseMl = doseMg / concentration;
  const doseUnits = doseMl * 100; // 100 units per 1ml on insulin syringe
  return {
    concentration: Math.round(concentration * 100) / 100,
    doseMl: Math.round(doseMl * 100) / 100,
    doseUnits: Math.round(doseUnits * 10) / 10,
  };
}

export function estimateRunOut(doseMg, frequencyHours, totalMg) {
  const mgPerDose = doseMg;
  const dosesAvailable = totalMg / mgPerDose;
  const totalHours = dosesAvailable * frequencyHours;
  return {
    dosesAvailable: Math.floor(dosesAvailable),
    daysAvailable: Math.round(totalHours / 24 * 10) / 10,
    lastDoseDate: new Date(Date.now() + totalHours * 60 * 60 * 1000),
  };
}